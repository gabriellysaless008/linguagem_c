#include <iostream>
using namespace std;

int main() {
    cout << "Hello World!\n";
    cout << 7 << "\n";

    // Comentário com mais de uma linha //
    cout << "Ruby " << "Jane" << endl;

    // inteiro //
    int num1 = 5;
    int num2;
    num2 = 10;
    cout << num1 << endl;
    cout << num2 << endl;
    
    // float //
    double numDecimal = 3.14;

    // char //
    char letra = 'S';
    string text = "Arriba!";

    // bool //
    bool isTrue = true;

    // imprimindo tudo //
    cout << "Double: " << numDecimal << endl;
    cout << "Char: " << letra << endl;
    cout << "String: " << text << endl;
    cout << "bool: " << isTrue << endl;


    return 0;
}